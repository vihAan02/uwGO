// Generates src/data/buildings/uw-buildings.generated.ts from the UW campus-map ArcGIS snapshot.
// Source: https://services5.arcgis.com/z87D0RdgTttiUQbV/arcgis/rest/services/BuildingsView/FeatureServer/0/query?where=1=1&outFields=*&f=geojson
import fs from "node:fs";
import path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname);
const src = path.join(here, "uw-buildings-arcgis-2026-09-08.geojson");
const out = path.join(here, "..", "src", "data", "buildings", "uw-buildings.generated.ts");

const geo = JSON.parse(fs.readFileSync(src, "utf8"));
const rows = [];
for (const f of geo.features) {
  const p = f.properties;
  if (!p.buildingCode || !f.geometry) continue;
  const [lng, lat] = f.geometry.coordinates;
  rows.push({
    code: String(p.buildingCode).trim(),
    name: String(p.buildingName ?? "").trim(),
    alternateNames: p.alternateBuildingNames
      ? String(p.alternateBuildingNames).split("|").map((s) => s.trim()).filter(Boolean)
      : [],
    parentCode: p.parentBuildingCode ? String(p.parentBuildingCode).trim() : undefined,
    buildingId: p.buildingId ? String(p.buildingId) : undefined,
    latitude: Number(lat.toFixed(7)),
    longitude: Number(lng.toFixed(7)),
  });
}
// De-duplicate: prefer the row with no parent (the complex itself) when a code appears twice.
const byCode = new Map();
for (const r of rows) {
  const prev = byCode.get(r.code);
  if (!prev || (prev.parentCode && !r.parentCode)) byCode.set(r.code, r);
}
const list = [...byCode.values()].sort((a, b) => a.code.localeCompare(b.code));
const body = list
  .map((r) => `  ${JSON.stringify(r)},`)
  .join("\n");
fs.writeFileSync(
  out,
  `// GENERATED by scripts/gen-uw-buildings.mjs — do not edit by hand.\n` +
    `// Source: University of Waterloo campus map Buildings feature service, snapshot 2026-09-08.\n` +
    `export interface UwBuildingRow { code: string; name: string; alternateNames: string[]; parentCode?: string; buildingId?: string; latitude: number; longitude: number }\n` +
    `export const UW_BUILDING_ROWS: readonly UwBuildingRow[] = [\n${body}\n];\n`,
);
console.log(`wrote ${list.length} buildings to ${path.relative(process.cwd(), out)}`);
